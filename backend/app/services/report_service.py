class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for dynamic page numbers (Page X of Y) and standard headers/footers."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: List[Any] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int) -> None:
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#767881"))

        # Header (pages after first)
        if self._pageNumber > 1:
            self.drawString(54, 750, "RoadVision AI — Road Damage Inspection Report")
            self.setStrokeColor(colors.HexColor("#D1D5DB"))
            self.setLineWidth(0.5)
            self.line(54, 744, letter[0] - 54, 744)

        # Footer
        footer_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 54, 36, footer_text)
        self.drawString(54, 36, "Confidential — Generated by RoadVision Intelligent Monitoring System")
        self.setStrokeColor(colors.HexColor("#D1D5DB"))
        self.setLineWidth(0.5)
        self.line(54, 48, letter[0] - 54, 48)

        self.restoreState()


class ReportService:
    """Generates PDF and CSV inspection deliverables."""

    def __init__(self, settings: Settings) -> None:
        self._settings = settings

    def generate_inspection_pdf(self, inspection_id: int) -> bytes:
        """Create a complete, formatted PDF inspection report."""
        record = get_inspection(self._settings, inspection_id)
        if record is None:
            raise ApiError(404, "inspection_not_found", "Inspection not found.")

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54,
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#111827"),
        )
        subtitle_style = ParagraphStyle(
            "DocSubTitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#4B5563"),
        )
        section_style = ParagraphStyle(
            "SectionHeader",
            parent=styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=13,
            leading=17,
            textColor=colors.HexColor("#1F2937"),
            spaceBefore=14,
            spaceAfter=6,
        )
        body_style = ParagraphStyle(
            "TableBody",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#374151"),
        )
        bold_style = ParagraphStyle(
            "TableBold",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#111827"),
        )

        elements: List[Any] = []

        # 1. Document Title & Subtitle
        elements.append(Paragraph("RoadVision AI — Inspection Report", title_style))
        created_str = record.get("created_at") or datetime.utcnow().isoformat()
        elements.append(
            Paragraph(f"Inspection Session ID: #{record['id']} &nbsp;|&nbsp; Generated: {created_str}", subtitle_style)
        )
        elements.append(Spacer(1, 10))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563EB"), spaceAfter=14))

        # 2. Executive Metadata Summary Table
        elements.append(Paragraph("1. Inspection Session Summary", section_style))
        summary_data = [
            [
                Paragraph("<b>Inspection ID:</b>", body_style),
                Paragraph(str(record["id"]), bold_style),
                Paragraph("<b>Input Type:</b>", body_style),
                Paragraph(str(record.get("input_type", "—")).upper(), bold_style),
            ],
            [
                Paragraph("<b>Source File:</b>", body_style),
                Paragraph(str(record.get("filename") or "Direct Stream / Camera"), body_style),
                Paragraph("<b>Status:</b>", body_style),
                Paragraph(str(record.get("status", "—")).upper(), bold_style),
            ],
            [
                Paragraph("<b>Detection Model:</b>", body_style),
                Paragraph(str(record.get("models_used") or "YOLO26m"), body_style),
                Paragraph("<b>Confidence Threshold:</b>", body_style),
                Paragraph(f"{record.get('conf_threshold', 0.25):.2f}", body_style),
            ],
            [
                Paragraph("<b>Total Defect Count:</b>", body_style),
                Paragraph(str(record.get("total_detections", 0)), bold_style),
                Paragraph("<b>Processing Duration:</b>", body_style),
                Paragraph(
                    f"{record['processing_ms']} ms" if record.get("processing_ms") else "—",
                    body_style,
                ),
            ],
        ]

        if record.get("input_type") in ("video", "webcam"):
            summary_data.append([
                Paragraph("<b>Frames Total:</b>", body_style),
                Paragraph(str(record.get("frames_total") or "—"), body_style),
                Paragraph("<b>Frames Processed:</b>", body_style),
                Paragraph(str(record.get("frames_processed", 0)), body_style),
            ])

        summary_table = Table(summary_data, colWidths=[110, 140, 110, 144])
        summary_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F9FAFB")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ])
        )
        elements.append(summary_table)
        elements.append(Spacer(1, 14))

        # 3. Defect Classification Breakdown
        elements.append(Paragraph("2. Road Damage Defect Classification", section_style))
        class_summary = record.get("class_summary") or {}
        if isinstance(class_summary, str):
            try:
                class_summary = json.loads(class_summary)
            except Exception:
                class_summary = {}

        class_rows = [
            [
                Paragraph("<b>Class Code</b>", bold_style),
                Paragraph("<b>Defect Description</b>", bold_style),
                Paragraph("<b>Severity / Category</b>", bold_style),
                Paragraph("<b>Count Detected</b>", bold_style),
            ]
        ]

        total_defs = record.get("total_detections", 0)
        for code in CLASS_CODES:
            cnt = int(class_summary.get(code, 0))
            desc = CLASS_LABELS.get(code, code)
            cat = "Structural Defect" if code == "D40" else "Surface Crack"
            class_rows.append([
                Paragraph(f"<b>{code}</b>", bold_style),
                Paragraph(desc, body_style),
                Paragraph(cat, body_style),
                Paragraph(str(cnt), bold_style if cnt > 0 else body_style),
            ])

        class_rows.append([
            Paragraph("<b>Total Defects</b>", bold_style),
            Paragraph("All Categories Combined", bold_style),
            Paragraph("—", body_style),
            Paragraph(str(total_defs), bold_style),
        ])

        breakdown_table = Table(class_rows, colWidths=[90, 180, 134, 100])
        breakdown_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EFF6FF")),
                ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
                ("TOPPADDING", (0, 0), (-1, 0), 6),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
                ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#F3F4F6")),
                ("TOPPADDING", (0, 1), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 1), (-1, -1), 5),
            ])
        )
        elements.append(breakdown_table)
        elements.append(Spacer(1, 14))

        # 4. Embedded Annotated Image (if output exists and is JPEG)
        output_name = record.get("output_name")
        if output_name and output_name.lower().endswith((".jpg", ".jpeg", ".png")):
            output_path = self._settings.outputs_dir / output_name
            if output_path.is_file():
                elements.append(Paragraph("3. Visual Defect Annotation Evidence", section_style))
                try:
                    # Max printable width ~ 500pt, aspect ratio preserved
                    img = Image(str(output_path), width=480, height=270, kind="proportional")
                    elements.append(KeepTogether([img, Spacer(1, 10)]))
                except Exception as exc:
                    log.warning("Could not embed image %s in PDF report: %s", output_path, exc)

        doc.build(elements, canvasmaker=NumberedCanvas)
        return buffer.getvalue()

    def export_history_csv(self, inspections: List[Dict[str, Any]]) -> str:
        """Export a list of inspection records into RFC 4180 compliant CSV."""
        output = io.StringIO()
        writer = csv.writer(output)

        headers = [
            "Inspection ID",
            "Created At",
            "Finished At",
            "Input Type",
            "Filename",
            "Model Used",
            "Confidence Threshold",
            "Status",
            "Total Detections",
            "D00 (Longitudinal Crack)",
            "D10 (Transverse Crack)",
            "D20 (Alligator Crack)",
            "D40 (Pothole)",
            "Frames Total",
            "Frames Processed",
            "Processing Time (ms)",
            "Output File",
        ]
        writer.writerow(headers)

        for item in inspections:
            counts = item.get("class_summary") or {}
            if isinstance(counts, str):
                try:
                    counts = json.loads(counts)
                except Exception:
                    counts = {}

            row = [
                item.get("id"),
                item.get("created_at"),
                item.get("finished_at") or "",
                item.get("input_type"),
                item.get("filename") or "",
                item.get("models_used") or "",
                item.get("conf_threshold") or "",
                item.get("status"),
                item.get("total_detections", 0),
                counts.get("D00", 0),
                counts.get("D10", 0),
                counts.get("D20", 0),
                counts.get("D40", 0),
                item.get("frames_total") or "",
                item.get("frames_processed", 0),
                item.get("processing_ms") or "",
                item.get("output_name") or "",
            ]
            writer.writerow(row)

        return output.getvalue()

